import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { generateKeyPairSync } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { disable, seal, stage, verifyBundle } from "./release.mjs";

test("seal, verify and roll back a local candidate using a disposable key", { skip: process.platform !== "linux" || process.arch !== "x64" }, (t) => {
  const dir = mkdtempSync(join(tmpdir(), "zaspctl-release-test-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const repo = join(dir, "source"), input = join(dir, "input"), checkout = join(dir,"web");
  for (const path of [repo, input, join(checkout,"app/features/tools")]) mkdirSync(path,{ recursive: true });
  const pin = join(checkout,"app/features/tools/cli-release-pin.json");
  writeFileSync(pin, "{}");
  writeFileSync(join(repo,"go.mod"), "module github.com/zasp-ai/zasp-sec/cmd/zaspctl\n\ngo 1.26.0\n");
  writeFileSync(join(repo,"main.go"), 'package main\nfunc main(){}\n');
  const git = (...args) => execFileSync("git", ["-C", repo, ...args], { encoding:"utf8", stdio:["ignore","pipe","pipe"] }).trim();
  git("init", "-q"); git("add", ".");
  git("-c","user.email=fixture@example.invalid","-c","user.name=Fixture","-c","commit.gpgsign=false","commit","-qm","release fixture");
  const commit = git("rev-parse","HEAD"), version = "v1.2.3", asset = "zaspctl-linux-amd64";
  execFileSync("go",["build","-C",repo,"-mod=readonly","-trimpath","-buildvcs=true","-o",join(input,asset),"."],
    {env:{...process.env,GOWORK:"off",GOPROXY:"off",GOTOOLCHAIN:"local",GOMAXPROCS:"1"}});
  const {publicKey,privateKey}=generateKeyPairSync("ed25519");
  const priv=join(dir,"private.pem"), pub=join(dir,"public.pem"), wrong=join(dir,"other.pem"), bundle=join(dir,"bundle");
  writeFileSync(priv,privateKey.export({format:"pem",type:"pkcs8"}),{mode:0o600});
  writeFileSync(pub,publicKey.export({format:"pem",type:"spki"}));
  writeFileSync(wrong,generateKeyPairSync("ed25519").publicKey.export({format:"pem",type:"spki"}));
  assert.throws(()=>seal(version,"1".repeat(40),priv,input,bundle), /commit/);
  seal(version,commit,priv,input,bundle);
  assert.throws(()=>verifyBundle(version,commit,wrong,bundle), /signature/);
  assert.throws(()=>verifyBundle("v1.2.2",commit,pub,bundle),/version/);
  const verified=verifyBundle(version,commit,pub,bundle);
  execFileSync("openssl",["pkeyutl","-verify","-pubin","-inkey",pub,"-rawin","-in",join(bundle,"manifest.json"),"-sigfile",join(bundle,"manifest.ed25519")],{stdio:"pipe"});
  assert.deepEqual(stage(version,commit,pub,bundle,checkout),verified);
  assert.deepEqual(JSON.parse(readFileSync(pin)),verified);
  assert.deepEqual(stage(version,commit,pub,bundle,checkout),verified);
  const next = join(dir,"next-bundle");
  seal("v1.2.4",commit,priv,input,next);
  stage("v1.2.4",commit,pub,next,checkout);
  assert.equal(JSON.parse(readFileSync(pin)).version,"v1.2.4");
  assert.deepEqual(stage(version,commit,pub,bundle,checkout),verified);
  disable(checkout);
  assert.equal(JSON.parse(readFileSync(pin)).assets.length,0);
  assert.deepEqual(stage(version,commit,pub,bundle,checkout),verified);
  writeFileSync(join(bundle,asset),"modified binary");
  assert.throws(()=>stage(version,commit,pub,bundle,checkout),/checksum/);
  assert.deepEqual(JSON.parse(readFileSync(pin)),verified);
  assert.throws(()=>seal(version,commit,priv,input,bundle),/already exists/);
});
