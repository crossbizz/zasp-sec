import getpass
import http.client
import json
import os
from pathlib import Path
import re
import selectors
import signal
import socket
import ssl
import stat
import subprocess
import sys
import tempfile
import uuid

ROOT = Path(__file__).resolve().parents[3]
OWNER = "zasp.io/installation"
LABEL = re.compile(r"[a-z0-9](?:[-a-z0-9]{0,61}[a-z0-9])?\Z")
ACTIONS = {"doctor", "status", "install", "upgrade", "start", "stop", "logs", "init", "unseal"}


class ServiceError(Exception):
    """Messages are suitable for operator output and contain no credentials."""


def setting(name, default=""):
    return os.environ.get("ZASP_VPS_" + name, default)


def trusted_directory(directory):
    for part in [directory, *directory.parents]:
        info = part.lstat()
        if not stat.S_ISDIR(info.st_mode) or info.st_uid not in (0, os.geteuid()):
            raise ServiceError("use a directory owned by the operator or root")
        if info.st_mode & 0o022 and (part == directory or not info.st_mode & stat.S_ISVTX):
            raise ServiceError("a credential directory allows untrusted writes")


def read_file(value, private=False, limit=131072):
    path = Path(value)
    if not path.is_absolute():
        raise ServiceError("a required file path must be absolute")
    try:
        trusted_directory(path.parent)
        fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)
        with os.fdopen(fd, "rb") as file:
            info = os.fstat(file.fileno())
            if (not stat.S_ISREG(info.st_mode) or info.st_uid not in (os.geteuid(), 0)
                    or info.st_mode & (0o077 if private else 0o022)):
                raise ServiceError("unsafe ownership, permissions, or type on a configured file")
            data = file.read(limit + 1)
            if not 0 < len(data) <= limit:
                raise ServiceError("configured file is empty or exceeds its size limit")
            return data
    except OSError:
        raise ServiceError("a required protected file is unavailable") from None


def command(args, label, payload=None, timeout=30):
    try:
        result = subprocess.run(args, input=payload, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        raise ServiceError(label + " unavailable or timed out") from None
    if result.returncode:
        raise ServiceError(label + " failed; check the explicit context, permissions and component prerequisites")
    return result.stdout


def decode(data):
    try:
        return json.loads(data)
    except (ValueError, UnicodeError):
        raise ServiceError("unexpected response format") from None


class Service:
    def __init__(self, component):
        self.name = component
        self.mode = self.config("MODE", "managed")
        self.ns = self.config("NAMESPACE", "openbao-system" if component == "openbao" else "connectors")
        self.context, self.uid, self.owner = (setting(key) for key in ("KUBE_CONTEXT", "CLUSTER_UID", "INSTALLATION_ID"))
        if self.mode not in ("managed", "existing") or not LABEL.fullmatch(self.ns):
            raise ServiceError("invalid component mode or namespace")
        self.port = 8200 if component == "openbao" else 8443
        expected = ("openbao." + self.ns + ".svc" if component == "openbao" else
                    "nango." + self.ns + ".svc.cluster.local")
        self.host = expected
        if self.config("URL", "https://" + expected + ":" + str(self.port)) != "https://" + expected + ":" + str(self.port):
            raise ServiceError("component URL must be the verified HTTPS authority generated by the production chart")
        self.workload = ("statefulset/openbao" if component == "openbao" else "deployment/nango")
        self.chart = ROOT / "deploy/vps" / component
        self.kube = ["kubectl", "--context", self.context, "--request-timeout=12s"]
        self.helm = ["helm", "--kube-context", self.context, "-n", self.ns]

    def config(self, key, default=""):
        return setting(self.name.upper() + "_" + key, default)

    def cluster(self):
        if not self.context or not self.uid or not LABEL.fullmatch(self.owner):
            raise ServiceError("set the VPS kube context, cluster UID and installation ID explicitly")
        try:
            uuid.UUID(self.uid)
        except ValueError:
            raise ServiceError("invalid expected cluster UID") from None
        actual = command(self.kube + ["get", "namespace", "kube-system", "-o", "jsonpath={.metadata.uid}"],
                         "cluster identity check").decode().strip()
        if actual != self.uid:
            raise ServiceError("Kubernetes cluster identity mismatch")

    def namespace(self, create=False):
        self.cluster()
        result = command(self.kube + ["get", "namespace", self.ns, "--ignore-not-found", "-o", "json"], "namespace lookup")
        if not result.strip():
            if not create:
                return False
            obj = {"apiVersion": "v1", "kind": "Namespace",
                   "metadata": {"name": self.ns, "labels": {OWNER: self.owner}}}
            command(self.kube + ["create", "-f", "-"], "create dedicated namespace", json.dumps(obj).encode())
            return True
        if decode(result).get("metadata", {}).get("labels", {}).get(OWNER) != self.owner:
            raise ServiceError("namespace belongs to another or unidentified installation")
        return True

    def release(self):
        rows = decode(command(self.helm + ["list", "--all", "--filter", "^" + self.name + "$", "-o", "json"],
                              "Helm release lookup"))
        if not isinstance(rows, list) or len(rows) > 1:
            raise ServiceError("ambiguous Helm release")
        if not rows:
            return None
        record = rows[0]
        if (record.get("name") != self.name or record.get("namespace") != self.ns
                or not re.fullmatch("zasp-" + self.name + r"-[0-9]+\.[0-9]+\.[0-9]+", record.get("chart", ""))):
            raise ServiceError("existing Helm release has a different owner or chart")
        return record.get("status")

    @contextmanager
    def connection(self):
        trust = self.config("CA_FILE")
        context = ssl.create_default_context(cadata=read_file(trust).decode("ascii")) if trust else ssl.create_default_context()
        context.minimum_version = ssl.TLSVersion.TLSv1_2
        proc = None
        try:
            address = (self.host, self.port)
            if self.mode == "managed":
                resource = "pod/openbao-0" if self.name == "openbao" else "service/nango"
                # --request-timeout applies to ordinary kubectl calls. The forward itself is long lived.
                proc = subprocess.Popen(["kubectl", "--context", self.context, "-n", self.ns, "port-forward",
                                         "--address", "127.0.0.1", "--pod-running-timeout=10s", resource,
                                         ":" + str(self.port)], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
                with selectors.DefaultSelector() as watcher:
                    watcher.register(proc.stdout, selectors.EVENT_READ)
                    if not watcher.select(13):
                        raise ServiceError("unavailable (private operator tunnel timed out)")
                    line = proc.stdout.readline(256).decode().strip()
                match = re.fullmatch(r"Forwarding from 127\.0\.0\.1:([0-9]+) -> " + str(self.port), line)
                if not match:
                    raise ServiceError("unavailable (private operator tunnel failed)")
                address = ("127.0.0.1", int(match[1]))
            yield API(self.host, self.port, address, context)
        finally:
            if proc is not None:
                proc.terminate()
                try:
                    proc.wait(3)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait()
                proc.stdout.close()

    def inspect(self, api):
        if self.name == "openbao":
            code, data = api.request("GET", "/v1/sys/health?standbyok=true")
            if code == 501 and data.get("initialized") is False:
                return "uninitialized (run secrets init openbao)" if self.mode == "managed" else "uninitialized (contact the service owner)"
            if code == 503 and data.get("sealed") is True:
                return "sealed (run secrets unseal openbao with the custodians)" if self.mode == "managed" else "sealed (contact the service owner)"
            if code != 200 or data.get("initialized") is not True or data.get("sealed") is not False:
                return "unavailable"
            file, path, header = self.config("STATUS_TOKEN_FILE"), "/v1/auth/token/lookup-self", "X-Vault-Token"
        else:
            code, data = api.request("GET", "/ready")
            if code != 200 or data.get("result") != "ok":
                return "unavailable"
            file, path, header = self.config("SERVICE_KEY_FILE"), "/api/v1/integrations", "Authorization"
        if not file:
            return "unauthenticated (a scoped status credential is required)"
        try:
            token = read_file(file, private=True, limit=16384).decode("ascii")
        except (ServiceError, UnicodeError):
            return "unauthenticated (status credential file unavailable or unsafe)"
        if token.endswith("\n"):
            token = token[:-1]
        if not re.fullmatch(r"[!-~]{8,16384}", token):
            raise ServiceError("invalid protected status credential")
        code, data = api.request("GET", path, headers={header: ("Bearer " if self.name == "nango" else "") + token})
        if code in (401, 403):
            return "unauthenticated"
        if code != 200:
            return "unavailable"
        if self.name == "nango":
            if not isinstance(data.get("data"), list):
                return "unavailable"
            return "healthy" if data["data"] else "healthy (no provider integrations configured)"
        policies = data.get("data", {}).get("policies")
        if not isinstance(policies, list) or not policies or "root" in policies:
            raise ServiceError("use a non-root scoped OpenBao status token")
        return "healthy"


class API:
    def __init__(self, name, port, address, context):
        self.name, self.port, self.address, self.context = name, port, address, context

    def request(self, method, path, data=None, headers=None):
        # Keep the verified server name independent of the loopback tunnel endpoint.
        req = http.client.HTTPSConnection(self.name, self.port, timeout=8, context=self.context)
        def expired(signum, frame):
            raise TimeoutError("component request timed out")

        original_signal = signal.signal(signal.SIGALRM, expired)
        signal.setitimer(signal.ITIMER_REAL, 12)
        try:
            with socket.create_connection(self.address, timeout=8) as raw_socket:
                req.sock = self.context.wrap_socket(raw_socket, server_hostname=self.name)
            payload = json.dumps(data).encode() if data is not None else None
            req.request(method, path, payload, {"Accept": "application/json", "Content-Type": "application/json", **(headers or {})})
            response = req.getresponse()
            raw = response.read(256 * 1024 + 1)
            if len(raw) > 256 * 1024 or 300 <= response.status < 400:
                raise ServiceError("unavailable (oversize response or unexpected redirect)")
            if response.status in (401, 403):
                return response.status, {}
            result = decode(raw) if raw else {}
            if not isinstance(result, dict):
                raise ServiceError("unexpected response format")
            return response.status, result
        except (OSError, http.client.HTTPException):
            raise ServiceError("unavailable (DNS, verified TLS or network failure)") from None
        finally:
            signal.setitimer(signal.ITIMER_REAL, 0)
            signal.signal(signal.SIGALRM, original_signal)
            req.close()


def pgp_recipients(service):
    directory = Path(service.config("PGP_KEYS_DIR"))
    keys, seen = [], set()
    with tempfile.TemporaryDirectory(prefix="zasp-gpg-") as gnupg:
        for name in [f"custodian-{i}.gpg" for i in range(1, 6)] + ["root.gpg"]:
            raw = read_file(str(directory / name))
            listing = command(["gpg", "--no-options", "--homedir", gnupg, "--batch", "--with-colons", "--show-keys"],
                              "verify a binary OpenPGP recipient key", raw).decode("utf-8").splitlines()
            rows = [line.split(":") for line in listing]
            pubs = [r for r in rows if r[0] == "pub"]
            fingerprints = [r[9] for r in rows if r[0] == "fpr"]
            if (raw.startswith(b"-----") or len(pubs) != 1 or not fingerprints or fingerprints[0] in seen
                    or pubs[0][1] in ("e", "r", "d") or "E" not in pubs[0][11]):
                raise ServiceError("use six distinct current binary OpenPGP encryption recipients")
            seen.add(fingerprints[0])
            keys.append(base64.b64encode(raw).decode())
    return keys


def encrypted_init_fields(result):
    shares = result.get("keys_base64")
    root = result.get("root_token")
    if not isinstance(shares, list) or len(shares) != 5 or not isinstance(root, str):
        raise ServiceError("ambiguous initialization result; use the recovery procedure")
    for ciphertext in shares + [root]:
        try:
            raw = base64.b64decode(ciphertext, validate=True)
            first = raw[0]
        except (TypeError, ValueError, IndexError):
            raise ServiceError("invalid encrypted initialization response") from None
        # OpenPGP public-key encrypted session-key packet (tag 1). Never persist clear shares or a clear root token.
        tag = first & 63 if first & 64 else (first >> 2) & 15
        if not first & 128 or tag != 1 or len(raw) < 32:
            raise ServiceError("server did not return encrypted recipient packets; follow the recovery procedure")
    return {"custodian_packets": shares, "bootstrap_packet": root}


def initialize(service, api):
    code, state = api.request("GET", "/v1/sys/init")
    if code != 200 or not isinstance(state.get("initialized"), bool):
        raise ServiceError("cannot establish OpenBao initialization state")
    if state["initialized"]:
        print("openbao: already initialized; use the original custodian handoff")
        return
    recipients = pgp_recipients(service)
    target = Path(service.config("HANDOFF_FILE"))
    if not target.is_absolute():
        raise ServiceError("set an absolute, new off-host encrypted handoff file")
    trusted_directory(target.parent)
    if target.parent.stat().st_mode & 0o077:
        raise ServiceError("handoff requires a private directory (0700)")
    try:
        fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except OSError:
        raise ServiceError("cannot reserve new protected handoff; existing files are preserved") from None
    with os.fdopen(fd, "wb") as out:
        out.write(b"pending: verify server state before another initialization\n")
        out.flush()
        os.fsync(out.fileno())
        parent = os.open(target.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(parent)
        finally:
            os.close(parent)
        code, record = api.request("PUT", "/v1/sys/init",
                                   {"secret_shares": 5, "secret_threshold": 3, "pgp_keys": recipients[:5],
                                    "root_token_pgp_key": recipients[5]})
        if code != 200:
            raise ServiceError("initialization did not complete; inspect seal state and retained handoff")
        encrypted = encrypted_init_fields(record)
        encrypted.update(installation=service.owner, cluster_uid=service.uid, namespace=service.ns)
        out.seek(0)
        out.write(json.dumps(encrypted).encode() + b"\n")
        out.truncate()
        out.flush()
        os.fsync(out.fileno())
    print("openbao: initialized; verify the off-host encrypted handoff and distribute to the six recipients")


def prompt_share():
    if not sys.stdin.isatty():
        raise ServiceError("unseal requires a private interactive terminal")
    # Fail before prompting if the terminal cannot disable echo. getpass's pipe fallback is forbidden.
    try:
        terminal = os.open("/dev/tty", os.O_RDWR)
        try:
            import termios
            attrs = termios.tcgetattr(terminal)
            termios.tcsetattr(terminal, termios.TCSANOW, attrs)
        finally:
            os.close(terminal)
        import warnings
        with warnings.catch_warnings():
            warnings.simplefilter("error", getpass.GetPassWarning)
            return getpass.getpass("One custodian's decrypted unseal share: ")
    except (OSError, EOFError, getpass.GetPassWarning):
        raise ServiceError("unseal requires a private interactive terminal") from None


def unseal(api):
    code, state = api.request("GET", "/v1/sys/seal-status")
    if code != 200 or state.get("initialized") is not True:
        raise ServiceError("OpenBao requires initialization before unseal")
    if state.get("sealed") is False:
        print("openbao: already unsealed")
        return
    if state.get("sealed") is not True or state.get("type") != "shamir":
        raise ServiceError("this operator flow requires a sealed Shamir installation")
    share = prompt_share()
    if not re.fullmatch(r"[A-Za-z0-9+/=]{16,256}", share):
        raise ServiceError("invalid share format")
    code, state = api.request("PUT", "/v1/sys/unseal", {"key": share})
    if code != 200 or not isinstance(state.get("sealed"), bool):
        raise ServiceError("share rejected; check source seal and custodian material")
    print("openbao: additional distinct custodian required" if state["sealed"] else "openbao: unsealed")


def render(service):
    try:
        import yaml
    except ImportError:
        raise ServiceError("install PyYAML for component preflight") from None
    values = service.config("VALUES_FILE")
    value_bytes = read_file(values, limit=1024 * 1024)
    try:
        if service.name == "nango":
            settings = yaml.safe_load(value_bytes)
            origin = os.environ.get("ZASP_ORIGIN", "")
            if not origin or not isinstance(settings, dict) or settings.get("publicOrigin") != origin:
                raise ServiceError("Nango publicOrigin must match the installation's ZASP_ORIGIN")
        chart = yaml.safe_load((service.chart / "Chart.yaml").read_text())
    except yaml.YAMLError:
        raise ServiceError("invalid chart metadata") from None
    if chart.get("name") != "zasp-" + service.name or chart.get("version") != "0.1.0":
        raise ServiceError("unrecognized bundled chart version")
    return command(["helm", "template", service.name, str(service.chart), "-n", service.ns, "-f", values],
                   "validate pinned component chart and values")


def check_inputs(service, rendered):
    try:
        import yaml
    except ImportError:
        raise ServiceError("install PyYAML for component preflight") from None
    try:
        resources = list(yaml.safe_load_all(rendered))
        template = next(doc for doc in resources if doc and doc.get("kind") in ("Deployment", "StatefulSet"))
        pod = template["spec"]["template"]["spec"]
        volumes = {v["name"]: v for v in pod["volumes"]}
        if service.name == "openbao":
            inputs = [("secret", volumes["tls"]["secret"]["secretName"], ["tls.crt", "tls.key", "ca.crt"])]
        else:
            inputs = [("secret", volumes["server-tls"]["secret"]["secretName"], ["tls.crt", "tls.key"]),
                      ("secret", volumes["storage"]["secret"]["secretName"], ["database-url", "service-key", "encryption-key"]),
                      ("configmap", volumes["db-ca"]["configMap"]["name"], ["ca.crt"])]
    except (KeyError, StopIteration, TypeError, yaml.YAMLError):
        raise ServiceError("cannot determine the chart's required startup inputs") from None
    for kind, name, keys in inputs:
        if not isinstance(name, str) or len(name) > 253 or not all(LABEL.fullmatch(part) for part in name.split(".")):
            raise ServiceError("invalid required resource name")
        # Kubernetes returns key names only, never secret values to the CLI.
        fmt = 'go-template={{range $k, $v := .data}}{{printf "%s\\n" $k}}{{end}}'
        found = command(service.kube + ["-n", service.ns, "get", kind, name, "--ignore-not-found", "-o", fmt],
                        "check protected startup resource").decode().splitlines()
        if not set(keys).issubset(found):
            raise ServiceError("required credential or trust input missing: " + kind + "/" + name)


def install(service, existing):
    if existing == "deployed":
        print(service.name + ": installed; existing release and settings preserved")
        return
    if existing:
        raise ServiceError("existing incomplete Helm release; inspect its revision and migration state before resuming")
    # All local chart/values validation precedes namespace creation.
    values = service.config("VALUES_FILE")
    rendered = render(service)
    service.namespace(create=True)
    check_inputs(service, rendered)
    # Prevent an install hook from overwriting resources left by another release.
    checks = ([service.workload, "service/openbao", "configmap/openbao-server", "networkpolicy/openbao",
               "persistentvolumeclaim/raft-openbao-0"] if service.name == "openbao" else
              [service.workload, "service/nango", "job/nango-migrate", "networkpolicy/nango-migrate",
               "networkpolicy/nango", "configmap/nango-tls-proxy"])
    found = command(service.kube + ["-n", service.ns, "get", *checks, "--ignore-not-found", "-o", "name"],
                    "check for unowned component resources")
    if found.strip():
        raise ServiceError("pre-existing component resources or Raft storage require an operator recovery review")
    args = service.helm + ["install", service.name, str(service.chart), "-f", values, "--timeout", "5m"]
    if service.name == "nango":
        args.append("--wait")
    command(args, "install versioned independent component", timeout=335)
    print(service.name + (": installed; inspect seal state, initialize once, then unseal" if service.name == "openbao"
                          else ": installed; verify authenticated status and provider setup"))


def owned_workload(service):
    doc = decode(command(service.kube + ["-n", service.ns, "get", service.workload, "-o", "json"],
                         "load component workload"))
    meta = doc.get("metadata", {})
    ann = meta.get("annotations", {})
    if (ann.get("meta.helm.sh/release-name") != service.name or ann.get("meta.helm.sh/release-namespace") != service.ns
            or meta.get("labels", {}).get("app.kubernetes.io/managed-by") != "Helm"):
        raise ServiceError("refusing mutation of workload outside this release")
    return doc


def run(action, component):
    if action not in ACTIONS or component not in ("openbao", "nango"):
        raise ServiceError("expected an independent component and a supported action")
    service = Service(component)
    if action in ("init", "unseal") and component != "openbao":
        raise ServiceError("initialization and unseal are OpenBao operations")
    if service.mode == "existing" and action in ("init", "unseal", "stop", "upgrade"):
        raise ServiceError("externally managed service; its owner controls this action")
    if os.environ.get("ZASP_DRY_RUN") == "1":
        print(f"{component}: dry run; {action} ({service.mode})")
        return
    release = None
    if service.mode == "managed":
        present = service.namespace()
        release = service.release() if present else None
        if action == "install":
            install(service, release)
            return
        if action == "doctor":
            rendered = render(service)
            if present:
                check_inputs(service, rendered)
            print(component + ": chart, cluster identity and namespace ownership checked" +
                  ("; existing release " + ("deployed" if release == "deployed" else "incomplete") if release else "; install required"))
            return
        if not release:
            raise ServiceError("component not installed in the selected cluster and namespace")
        if action in ("start", "status") and release != "deployed":
            raise ServiceError("incomplete component release; review its revision and migration state")
        if action == "upgrade":
            raise ServiceError("automatic upgrade requires an installation- and release-bound verified recovery checkpoint; follow the operator runbook")
        if action in ("stop", "start"):
            workload = owned_workload(service)
            replicas = 0 if action == "stop" else 1
            old = workload["spec"]["replicas"]
            if old != replicas:
                if old not in (0, 1):
                    raise ServiceError("refusing to change an unexpected replica count")
                # Preconditions detect a concurrent reinstall or scale.
                command(service.kube + ["-n", service.ns, "scale", service.workload,
                                        "--resource-version=" + workload["metadata"]["resourceVersion"],
                                        "--current-replicas=" + str(old), "--replicas=" + str(replicas)],
                        "scale independent component")
            if action == "stop":
                print(component + ": stopped; persistent storage retained")
                return
        if action == "logs":
            doc = owned_workload(service)
            uid = doc["metadata"]["uid"]
            events = command(service.kube + ["-n", service.ns, "get", "events", "--field-selector",
                                             "involvedObject.uid=" + uid, "--no-headers",
                                             "-o", "custom-columns=TYPE:.type"], "read lifecycle events")
            counts = {"Normal": 0, "Warning": 0, "Other": 0}
            for key in events.decode().splitlines():
                counts[key if key in ("Normal", "Warning") else "Other"] += 1
            print(component + ": workload event records; " + ", ".join(f"{k}={v}" for k, v in counts.items()))
            return
    elif action == "logs":
        raise ServiceError("externally managed service; use its operator's protected log access")
    elif action == "doctor":
        if service.config("CA_FILE"):
            ssl.create_default_context(cadata=read_file(service.config("CA_FILE")).decode("ascii"))
        print(component + ": external TLS authority configured; status verifies live authentication")
        return
    with service.connection() as api:
        if action == "init":
            initialize(service, api)
        elif action == "unseal":
            unseal(api)
        else:
            status = service.inspect(api)
            if not status.startswith("healthy"):
                raise ServiceError(status)
            print(component + ": " + status)


def main(args):
    component = args[1] if len(args) == 2 and args[1] in ("openbao", "nango") else "component"
    try:
        if len(args) != 2:
            raise ServiceError("expected ACTION openbao|nango")
        run(*args)
        return 0
    except ServiceError as exc:
        print(component + ": " + str(exc), file=sys.stderr)
    except (OSError, UnicodeError, ValueError, TypeError, KeyError, http.client.HTTPException):
        # OS, TLS, server and parser errors may include secret paths, response bodies or host data.
        print(component + ": unavailable or invalid private configuration", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
